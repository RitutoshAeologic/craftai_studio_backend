import os
import re
import uuid
import httpx
from typing import List, Dict, Any, Optional
from app.infrastructure.clients.base import IDiffusionGateway, IDiffusionEngine, IVisionClient, IFaceLockEngine, ICloudDiffusionEngine
from app.infrastructure.clients.diffusion_factory import DiffusionStrategyFactory
from app.infrastructure.clients.vision_factory import VisionClientFactory
from app.infrastructure.storage.storage_provider import IStorageProvider, StorageFactory
from app.infrastructure.clients.gemini_client import GeminiVisionClient
from app.infrastructure.clients.huggingface_client import HuggingFaceClient
from app.infrastructure.clients.diffusion_engine import CompositeDiffusionEngine
from app.infrastructure.storage.task_store import ITaskStore
from app.schemas.generation import GenerationDispatchRequest, GenerationDispatchResponse, GenerationStatusResponse
from app.services.wallet_service import IWalletService, SupabaseWalletService
from app.core.supabase_client import get_supabase_admin
from app.core.logging import logger

class GenerationService:
    def __init__(
        self,
        diffusion_gateway: IDiffusionGateway,
        task_store: ITaskStore,
        gemini_vision: Optional[IVisionClient] = None,
        hf_client: Optional[HuggingFaceClient] = None,
        diffusion_engine: Optional[IDiffusionEngine] = None,
        wallet_service: Optional[IWalletService] = None,
        facelock_engine: Optional[IFaceLockEngine] = None,
        cloud_diffusion: Optional[ICloudDiffusionEngine] = None,
        storage_provider: Optional[IStorageProvider] = None
    ):
        self.diffusion_gateway = diffusion_gateway
        self.task_store = task_store
        self.gemini_vision = gemini_vision or VisionClientFactory.get_vision_client()
        self.hf_client = hf_client or HuggingFaceClient()
        self.diffusion_engine = diffusion_engine or CompositeDiffusionEngine(hf_client=self.hf_client)
        self.wallet_service = wallet_service or SupabaseWalletService()
        self.facelock_engine = facelock_engine or DiffusionStrategyFactory.get_facelock_engine()
        self.cloud_diffusion = cloud_diffusion or DiffusionStrategyFactory.get_cloud_diffusion_engine()
        self.storage_provider = storage_provider or StorageFactory.get_storage_provider()

    async def _upload_to_supabase_storage(self, image_bytes: bytes, file_prefix: str = "gen") -> Optional[str]:
        """Delegates asset upload to active IStorageProvider."""
        return await self.storage_provider.upload(image_bytes, folder="user_generations", file_prefix=file_prefix, ext="png", content_type="image/png")

    async def _save_local_media_fallback(self, image_bytes: bytes, task_id: str) -> Optional[str]:
        """Saves generated bytes to local disk storage for offline/dev serving when Supabase Storage is unconfigured."""
        try:
            from pathlib import Path
            storage_dir = Path(__file__).resolve().parent.parent.parent / "storage" / "generations"
            storage_dir.mkdir(parents=True, exist_ok=True)
            file_path = storage_dir / f"{task_id}.png"
            with open(file_path, "wb") as f:
                f.write(image_bytes)
            logger.info(f"[Local Media] Saved offline fallback image to {file_path}")
            return f"/api/v1/media/{task_id}.png"
        except Exception as err:
            logger.error(f"[Local Media] Failed to save local fallback: {err}")
            return None

    async def dispatch(self, req: GenerationDispatchRequest, user_id: Optional[str] = None) -> GenerationDispatchResponse:
        task_id = req.task_id if req.task_id else f"gen_{os.urandom(4).hex()}"
        has_face_lock = bool(req.face_reference_urls and len(req.face_reference_urls) > 0) or bool(req.character_id)
        effective_prompt = req.prompt.strip()
        cost = 3.0 if has_face_lock else 2.0

        if user_id:
            await self.wallet_service.deduct_credits(
                user_id=user_id,
                amount=cost,
                task_id=task_id,
                reason="image_generation"
            )

        # ── 1. Multimodal Facial Identity Conditioning ────────────────────────
        extracted_face_tokens = None
        ref_url = None
        if req.face_reference_urls and len(req.face_reference_urls) > 0:
            ref_url = req.face_reference_urls[0]
            try:
                logger.info(f"[Face-Lock] Downloading reference selfie for facial conditioning: {ref_url}")
                async with httpx.AsyncClient(timeout=10.0) as client:
                    img_resp = await client.get(ref_url)
                    if img_resp.status_code == 200:
                        mime = img_resp.headers.get("content-type", "image/png").split(";")[0]
                        extracted_face_tokens = await self.gemini_vision.extract_facial_identity(
                            img_resp.content, mime_type=mime
                        )
                    else:
                        logger.warning(f"[Face-Lock] Reference photo download returned HTTP {img_resp.status_code}")
            except Exception as e:
                logger.error(f"[Face-Lock] Error extracting facial identity: {e}")

        if extracted_face_tokens:
            cleaned = re.sub(r'^(using\s+(my\s+)?(uploaded\s+)?photo(\s*,)?\s*)', '', effective_prompt, flags=re.IGNORECASE)
            cleaned = re.sub(r'preserve\s+my\s+identity(\s*,)?\s*', '', cleaned, flags=re.IGNORECASE)
            effective_prompt = f"Portrait of a {extracted_face_tokens}, {cleaned.strip()}"
            logger.info(f"[Face-Lock] Synthesized identity-conditioned prompt: {effective_prompt[:150]}...")

        # ── 2. Route Generation Engine (InstantID vs SDXL Lightning vs FLUX.1) ─
        direct_url = None
        tier_label = "Tier 0 (SDXL-Lightning RealVisXL Engine)"

        if has_face_lock and ref_url:
            tier_label = "Tier 1 (InstantID Face-Lock via Hugging Face)"
            try:
                logger.info("[Generation] Invoking Hugging Face InstantID for 100% Face Preservation...")
                instant_bytes = await self.facelock_engine.generate_with_face(
                    face_image_url_or_path=ref_url,
                    prompt=effective_prompt,
                    negative_prompt=req.negative_prompt,
                    seed=req.seed or 42
                )
                if instant_bytes:
                    direct_url = await self._upload_to_supabase_storage(instant_bytes, file_prefix="instantid")
                    if not direct_url:
                        direct_url = await self._save_local_media_fallback(instant_bytes, task_id)
                    if direct_url:
                        logger.info(f"[Generation] InstantID successfully uploaded: {direct_url}")
            except Exception as e:
                logger.error(f"[Generation] InstantID generation encountered error: {e}")
        else:
            # 2a. Primary: Composite Diffusion Engine (Sidecar on Port 8001 / Local MPS / HF)
            try:
                logger.info(f"[Generation] Invoking Diffusion Engine for prompt: '{effective_prompt[:60]}...'")
                gen_bytes = await self.diffusion_engine.generate_image(
                    prompt=effective_prompt,
                    width=req.width or 1024,
                    height=req.height or 1024,
                    seed=req.seed or 42,
                    negative_prompt=req.negative_prompt
                )
                if gen_bytes:
                    direct_url = await self._upload_to_supabase_storage(gen_bytes, file_prefix="sdxl")
                    if not direct_url:
                        direct_url = await self._save_local_media_fallback(gen_bytes, task_id)
                    if direct_url:
                        tier_label = "Tier 0 (SDXL-Lightning RealVisXL Engine)"
                        logger.info(f"[Generation] SDXL generation uploaded: {direct_url}")
            except Exception as e:
                logger.warning(f"[Generation] Diffusion Engine failed: {e}")

            # 2b. Secondary Fallback: Direct Hugging Face FLUX.1
            if not direct_url:
                try:
                    logger.info("[Generation] Falling back to Hugging Face FLUX.1-schnell...")
                    flux_bytes = await self.cloud_diffusion.generate_flux(
                        prompt=effective_prompt,
                        width=req.width or 1024,
                        height=req.height or 1024,
                        seed=req.seed or 42
                    )
                    if flux_bytes:
                        direct_url = await self._upload_to_supabase_storage(flux_bytes, file_prefix="flux")
                        if not direct_url:
                            direct_url = await self._save_local_media_fallback(flux_bytes, task_id)
                        if direct_url:
                            tier_label = "Tier 0 (FLUX.1-schnell via Hugging Face)"
                            logger.info(f"[Generation] FLUX.1 successfully uploaded: {direct_url}")
                except Exception as e:
                    logger.error(f"[Generation] FLUX.1 generation encountered error: {e}")

        # Fallback to direct safe URL if cloud generation did not return a permanent URL
        if not direct_url:
            logger.warning("[Generation] All image synthesis engines unavailable, falling back to safe gateway...")
            direct_url = self.diffusion_gateway.build_safe_url(
                prompt=effective_prompt,
                width=req.width or 1024,
                height=req.height or 1024,
                seed=req.seed or 42,
                model="flux"
            )

        # ── 3. Record Task in State Store ─────────────────────────────────────
        self.task_store.save_task(task_id, {
            "tier": tier_label,
            "status": "completed",
            "progress": 100,
            "output_url": direct_url,
            "prompt": effective_prompt,
            "has_face_lock": has_face_lock,
            "extracted_features": extracted_face_tokens
        })

        # ── 4. Cloud Persistence: Attempt Supabase Jobs Table Insert ──────────
        if user_id and user_id != "00000000-0000-0000-0000-000000000000":
            try:
                admin = get_supabase_admin()
                admin.table("jobs").insert({
                    "id": str(uuid.uuid4()),
                    "job_id": task_id,
                    "user_id": user_id,
                    "type": "IMAGE_GEN",
                    "status": "completed",
                    "prompt_text": effective_prompt,
                    "prompt": effective_prompt,
                    "model_used": "sdxl_lightning" if "SDXL" in tier_label else "flux",
                    "preview_image_url": direct_url,
                    "preview_url": direct_url,
                    "tool_applied": "face_lock" if has_face_lock else "text_to_image",
                    "aspect_ratio": f"{req.width}:{req.height}" if req.width and req.height else "1:1",
                    "dimensions": f"{req.width or 1024}x{req.height or 1024}",
                    "seed": req.seed or 42,
                    "credits_deducted": cost,
                    "is_download_unlocked": False,
                    "metadata": req.structured_metadata or {}
                }).execute()
                logger.info(f"[Cloud Jobs] Persisted generation {task_id} for user {user_id}")
            except Exception as e:
                logger.debug(f"[Cloud Jobs] Table save skipped or pending migration: {e}")

        return GenerationDispatchResponse(
            task_id=task_id,
            tier=tier_label,
            status="ready",
            estimated_seconds=18 if has_face_lock else 6,
            direct_image_url=direct_url
        )

    def get_status(self, task_id: str) -> GenerationStatusResponse:
        task = self.task_store.get_task(task_id)
        if not task:
            fallback_url = self.diffusion_gateway.build_safe_url("cyberpunk visual masterpiece")
            return GenerationStatusResponse(
                task_id=task_id,
                status="completed",
                progress=100,
                output_url=fallback_url
            )
        return GenerationStatusResponse(
            task_id=task_id,
            status=task.get("status", "unknown"),
            progress=task.get("progress", 0),
            output_url=task.get("output_url")
        )

    def get_websocket_phases(self, task_id: str) -> List[Dict[str, Any]]:
        task = self.task_store.get_task(task_id) or {}
        has_face_lock = task.get("has_face_lock", False)

        if has_face_lock:
            return [
                {"progress": 20, "status": "scanning_face", "message": "Gemini scanning facial contours..."},
                {"progress": 50, "status": "locking_identity", "message": "InstantID locking identity vectors..."},
                {"progress": 80, "status": "rendering", "message": "Synthesizing styled portrait with preserved identity..."},
                {"progress": 100, "status": "completed", "message": "Identity-locked master rendered!"}
            ]
        else:
            return [
                {"progress": 20, "status": "queued", "message": "Preparing SDXL Lightning diffusion engine..."},
                {"progress": 50, "status": "compiling", "message": "Compiling diffusion prompt tokens..."},
                {"progress": 80, "status": "diffusing", "message": "RealVisXL generating photorealistic latents on Metal MPS..."},
                {"progress": 100, "status": "completed", "message": "High-fidelity visual generation complete!"}
            ]
